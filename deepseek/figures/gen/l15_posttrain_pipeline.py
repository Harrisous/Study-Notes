"""Figure 15.6: the DeepSeek-V3.2 post-training pipeline (schematic).

Source: V3.2 paper section 3 ("Specialist Distillation", "Mixed RL Training",
"DeepSeek-V3.2 and DeepSeek-V3.2-Speciale"): six specialised domains plus writing and general QA,
every specialist fine-tuned from the same V3.2 base and trained with large-scale RL; thinking and
non-thinking data generated by different models; one mixed GRPO stage with rule-based outcome reward,
length penalty and language-consistency reward (reasoning / agent) and a generative reward model with
per-prompt rubrics (general tasks). Speciale: reasoning data only, reduced length penalty,
DeepSeekMath-V2 data and reward. Budget: "exceeding 10% of the pre-training cost".
Writes deepseek/figures/l15-posttrain-pipeline.svg
"""

from l15_svg import SVG

W, H = 760, 470
svg = SVG(W, H, "DeepSeek-V3.2 的后训练：专家各自做 RL，蒸馏成一个模型，再做一次混合 RL")

# ---------------------------------------------------------------- column 1: base
svg.box(12, 176, 104, 76, [("V3.2 基座", {"weight": "700"}), ("DSA 续训后", {"size": 12, "color": "muted"}),
                          ("的检查点", {"size": 12, "color": "muted"})], color="ink", fill_opacity=0.05)

# ---------------------------------------------------------------- column 2: specialists
DOM = ["数学", "编程", "通用逻辑推理", "通用智能体", "智能体编程", "智能体搜索", "写作", "通用问答"]
SX, SW, SH, SY0, GAP = 156, 150, 30, 40, 7
svg.text(SX + SW / 2, 28, "8 个专家（同一基座出发）", size=12, anchor="middle", weight="700")
ys = []
for i, d in enumerate(DOM):
    y = SY0 + i * (SH + GAP)
    ys.append(y + SH / 2)
    six = i < 6
    svg.rect(SX, y, SW, SH, fill="blue", fill_opacity=0.10 if six else 0.04, stroke="blue", width=1.1, rx=5,
             dash=None if six else "4 3")
    svg.text(SX + 10, y + 20, d, size=12)
    svg.rect(SX + SW - 40, y + 7, 32, 16, fill="blue", fill_opacity=0.18, rx=3)
    svg.text(SX + SW - 24, y + 19, "RL", size=11, anchor="middle", color="blue", weight="700")
    svg.line(116, 214, SX - 2, y + SH / 2, color="muted", width=0.9)
svg.text(SX + SW / 2, SY0 + 8 * (SH + GAP) + 10, "实线 6 个：论文所说的“专门领域”", size=11, anchor="middle", color="muted")
svg.text(SX + SW / 2, SY0 + 8 * (SH + GAP) + 25, "虚线 2 个：写作与通用问答", size=11, anchor="middle", color="muted")

# ---------------------------------------------------------------- column 3: generated data
DX, DW = 346, 142
svg.text(DX + DW / 2, 28, "专家生成训练数据", size=12, anchor="middle", weight="700")
svg.box(DX, 70, DW, 58, [("思考模式数据", {"weight": "700"}), ("长思维链", {"size": 12, "color": "muted"})],
        color="amber", fill_opacity=0.12)
svg.box(DX, 146, DW, 58, [("非思考模式数据", {"weight": "700"}), ("直接回答", {"size": 12, "color": "muted"})],
        color="amber", fill_opacity=0.12)
svg.text(DX + DW / 2, 222, "两类数据由不同的模型生成", size=11, anchor="middle", color="muted")
for y in ys:
    svg.line(SX + SW + 2, y, DX - 4, 137, color="muted", width=0.8)
svg.arrow(DX + DW / 2, 232, DX + DW / 2, 262, color="ink", width=1.5)
svg.box(DX, 264, DW, 70, [("蒸馏（SFT）", {"weight": "700"}), ("→ 一个检查点", {"size": 12}),
                          ("只比专家略差，RL 后抹平", {"size": 11, "color": "muted"})], color="blue",
        fill_opacity=0.10, line_gap=18)

# ---------------------------------------------------------------- column 4: mixed RL
RX, RW = 520, 228
svg.arrow(DX + DW + 2, 299, RX - 4, 262, color="ink", width=1.5)
svg.rect(RX, 110, RW, 196, fill="blue", fill_opacity=0.06, stroke="blue", width=1.4, rx=8)
svg.text(RX + RW / 2, 132, "混合 RL：一个阶段（GRPO）", size=13, anchor="middle", weight="700")
svg.text(RX + RW / 2, 150, "推理、智能体、人类对齐合在一起", size=12, anchor="middle", color="muted")
svg.box(RX + 10, 162, RW - 20, 62, [("推理与智能体任务", {"weight": "700", "size": 12}),
                                    ("规则判定的结果奖励", {"size": 12}), ("+ 长度惩罚 + 语言一致性奖励", {"size": 12})],
        color="green", fill_opacity=0.10, line_gap=17)
svg.box(RX + 10, 232, RW - 20, 62, [("通用任务", {"weight": "700", "size": 12}),
                                    ("生成式奖励模型", {"size": 12}), ("+ 每道题自己的评分细则", {"size": 12})],
        color="green", fill_opacity=0.10, line_gap=17)
svg.arrow(RX + RW / 2, 308, RX + RW / 2, 330, color="ink", width=1.5)
svg.box(RX + 30, 332, RW - 60, 40, [("DeepSeek-V3.2", {"weight": "700"})], color="blue", fill_opacity=0.18)
svg.text(RX + RW / 2, 390, "数千步混合 RL 之后的最终检查点", size=11, anchor="middle", color="muted")
svg.text(RX + RW / 2, 60, "后训练预算：", size=12, anchor="middle", color="ink")
svg.text(RX + RW / 2, 78, "“超过预训练成本的 10%”", size=12, anchor="middle", color="ink", weight="700")

# ---------------------------------------------------------------- Speciale branch
BY = 394
svg.arrow(DX + DW / 2, 336, DX + DW / 2, BY - 2, color="muted", width=1.3, dash="5 4")
svg.box(DX - 14, BY, DW + 28, 40, [("DeepSeek-V3.2-Speciale", {"weight": "700"})], color="ink", fill_opacity=0.05,
        dash="5 3")
svg.text(12, BY + 4, "另一条 RL 分支：", size=12, color="ink", weight="700")
svg.text(12, BY + 22, "只用推理数据、减小长度惩罚，", size=12, color="ink")
svg.text(12, BY + 40, "并入 DeepSeekMath-V2 的数据与奖励", size=12, color="ink")
svg.text(12, 462, "据 DeepSeek-V3.2 论文第 3 节绘制。V3.2-Exp 的报告列出的专门领域是 5 个（没有“通用智能体”）。", size=11,
         color="muted")

svg.save("l15-posttrain-pipeline.svg")
